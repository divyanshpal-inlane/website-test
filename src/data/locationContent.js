// Case-insensitive lookup so "Whitefield" / "whitefield" / "WHITEFIELD" all work
export const getLocationContent = (location) => {
  if (!location) return null;
  const key = Object.keys(locationContent).find(
    (k) => k.toLowerCase() === location.toLowerCase(),
  );
  return key ? locationContent[key] : null;
};

// Returns just the practice routes string for SwipableBenefits.jsx Card 3
export const getPracticeRoutes = (location) => {
  const content = getLocationContent(location);
  return content?.practiceRoutes || `popular routes around ${location}`;
};

export default locationContent;
